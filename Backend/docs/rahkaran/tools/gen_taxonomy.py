"""Generate sql/rahkaran/15_taxonomy.sql (view ai.account_taxonomy) and docs/rahkaran/TAXONOMY_REVIEW.md from the accountant's workbook
docs/rahkaran/data/mehvargostar_code.xlsx (columns: Subsidiary_Code, Subsidiary_Name, Profit_Loss_Statement, Detail_Income_Cost).

Rows of the workbook are authoritative (taxonomy_source = 'accountant'). Cost accounts that are mirrors of a workbook row but are missing from it
(5111xx / 5112xx / 5114xx twins of the 1117xx accounts, other 1117xx/6213xx accounts) get the category of the matching workbook row, found by
(1) the same 2-digit suffix as the 1117xx row if the titles agree (similarity >= 0.6), else (2) a near-identical title (>= 0.85);
taxonomy_source = 'derived'. Everything else stays unclassified and is listed in TAXONOMY_REVIEW.md for the accountant.

Env: RAHKARAN_SA_PASSWORD (+ RAHKARAN_HOST, RAHKARAN_PORT, RAHKARAN_DB). Run, then `python sql/rahkaran/apply.py 15 20 30 40 descr`.
"""
import difflib, os, re, sys
import openpyxl
import pymssql

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..")
XLSX = os.path.join(ROOT, "docs", "rahkaran", "data", "mehvargostar_code.xlsx")
OUT_SQL = os.path.join(ROOT, "sql", "rahkaran", "15_taxonomy.sql")
OUT_MD = os.path.join(ROOT, "docs", "rahkaran", "TAXONOMY_REVIEW.md")
FAMILIES = ("1117", "5111", "5112", "5114", "6213")


def norm(s):
    s = re.sub(r"[\s\-\(\)،,\*\d]", "", str(s)).replace("ي", "ی").replace("ك", "ک").replace("أ", "ا")
    return s


def sim(a, b):
    return difflib.SequenceMatcher(None, norm(a), norm(b)).ratio()


def q(s):
    return "N'" + str(s).replace("'", "''") + "'"


def main():
    rows = []
    for r in list(openpyxl.load_workbook(XLSX, read_only=True).active.iter_rows(values_only=True))[1:]:
        code = str(r[0]).strip() if r[0] is not None else ""
        if not re.fullmatch(r"\d{6}", code):
            print("skipped (not a 6-digit moin code):", r[:4])
            continue
        rows.append((code, str(r[1]).strip(), (r[2] or "").strip(), (r[3] or "").strip() or None))
    explicit = {c: (n, s, d) for c, n, s, d in rows}

    conn = pymssql.connect(os.environ.get("RAHKARAN_HOST", "127.0.0.1"), user="sa", password=os.environ["RAHKARAN_SA_PASSWORD"],
                           database=os.environ.get("RAHKARAN_DB", "MehvarGostar"), port=int(os.environ.get("RAHKARAN_PORT", "14330")), charset="UTF-8")
    cur = conn.cursor()
    cur.execute("SELECT sl_code, sl_title, has_postings FROM ai.accounts")
    db = {c: (t.strip(), p) for c, t, p in cur.fetchall()}

    base = {c[4:]: v for c, v in explicit.items() if c.startswith("1117")}
    cost_rows = [(c, v) for c, v in explicit.items() if c[:4] in FAMILIES and v[2]]
    derived, unclassified = {}, []
    for code, (title, posted) in sorted(db.items()):
        if code in explicit or code[:4] not in FAMILIES:
            continue
        hit = None
        b = base.get(code[4:])
        if b and b[2] and sim(title, b[0]) >= 0.6:
            hit = (b, "suffix")
        else:
            best = max(cost_rows, key=lambda cv: sim(title, cv[1][0]), default=None)
            if best and sim(title, best[1][0]) >= 0.85:
                hit = (best[1], "title")
        if hit:
            derived[code] = (title, hit[0][1], hit[0][2])
        else:
            unclassified.append((code, title, posted))

    lines = ["-- GENERATED by docs/rahkaran/tools/gen_taxonomy.py from docs/rahkaran/data/mehvargostar_code.xlsx - do not edit by hand.",
             "-- ai.account_taxonomy: the accountant's classification of moin (SL) accounts: P&L statement section -> detail category.",
             "-- taxonomy_source = 'accountant' (listed in the workbook) or 'derived' (mirror account of a listed one, e.g. 5111xx twin of 1117xx).",
             "CREATE OR ALTER VIEW ai.account_taxonomy AS",
             "SELECT sl_code, source_sl_name, pnl_statement, detail_category, taxonomy_source",
             "FROM (VALUES"]
    vals = [(c, n, s, d, "accountant") for c, (n, s, d) in sorted(explicit.items())]
    vals += [(c, t, s, d, "derived") for c, (t, s, d) in sorted(derived.items())]
    lines.append(",\n".join(f"  ({q(c)}, {q(n)}, {q(s)}, {q(d) if d else 'NULL'}, {q(src)})" for c, n, s, d, src in vals))
    lines.append(") AS t(sl_code, source_sl_name, pnl_statement, detail_category, taxonomy_source);")
    lines.append("GO\n")
    open(OUT_SQL, "w", encoding="utf-8").write("\n".join(lines))

    cats = {}
    for c, n, s, d, src in vals:
        if d:
            cats.setdefault((s, d), []).append((c, n, src))
    md = ["# طبقه‌بندی حسابدار (ai.account_taxonomy) - گزارش بازبینی\n",
          f"منبع: `docs/rahkaran/data/mehvargostar_code.xlsx` ({len(explicit)} معین از حسابدار) + {len(derived)} معین مشتق‌شده (آینه‌ی معین‌های فهرست‌شده). تولید خودکار با `tools/gen_taxonomy.py`.\n",
          "## معین‌هایی که در فایل حسابدار نیستند و طبقه‌ای نگرفتند (نیاز به نظر حسابدار)\n",
          "ستون «ثبت‌شده» یعنی در دفتر کل ردیف سند دارد. فقط خانواده‌ی 1117/5111/5112/5114/6213 بررسی شده است.\n",
          "| کد | عنوان | ثبت‌شده |", "|---|---|---|"]
    md += [f"| {c} | {t} | {'بله' if p else 'خیر'} |" for c, t, p in unclassified if p] 
    md += ["\nمعین‌های بدون ردیف سند (بی‌اهمیت): " + "، ".join(c for c, t, p in unclassified if not p) + "\n",
           "## معین‌های مشتق‌شده (باید تأیید شوند)\n", "| کد | عنوان | طبقه |", "|---|---|---|"]
    md += [f"| {c} | {t} | {d} |" for c, (t, s, d) in sorted(derived.items())]
    md += ["\n## دسته‌ها\n"] + [f"- **{d}** ({s}): {len(v)} معین" for (s, d), v in sorted(cats.items())]
    open(OUT_MD, "w", encoding="utf-8").write("\n".join(md) + "\n")
    print(f"{len(explicit)} explicit, {len(derived)} derived, {len(unclassified)} unclassified ({sum(1 for u in unclassified if u[2])} with postings)")


if __name__ == "__main__":
    main()
